/** @jest-environment node */
import PDFExportService from "./pdfExportService";
import { sbomConformance } from "../utils/conformance";

const SBOM = {
  bomFormat: "CycloneDX", specVersion: "1.5", serialNumber: "urn:uuid:3e671687-395b-41f5-a30f-a58921a69b79", version: 1,
  metadata: {
    timestamp: "2026-11-20T10:00:00Z", authors: [{ name: "Example Org PSIRT" }],
    tools: { components: [{ type: "application", name: "syft", version: "1.18.0" }] }, // CycloneDX 1.5 object form
    component: { "bom-ref": "app", name: "payments-service", version: "4.1.0" },
    properties: [{ name: "cert-in:distribution", value: "private" }, { name: "cert-in:practice:frequency", value: "Every release" }],
  },
  components: [
    { "bom-ref": "lodash", type: "library", name: "lodash", version: "4.17.20", purl: "pkg:npm/lodash@4.17.20",
      description: "Lodash modular utilities.", licenses: [{ license: { id: "MIT" } }], hashes: [{ alg: "SHA-1", content: "b58f" }],
      properties: [
        { name: "Patch Status", value: "Update available (>= 4.17.21)" }, { name: "Release Date", value: "13-08-2020" },
        { name: "End-of-Life Date", value: "NA" }, { name: "Criticality", value: "High" },
        { name: "Usage Restrictions", value: "Permissive licence - attribution required; export control not assessed" },
        { name: "Comments or Notes", value: "4 known vulnerabilities" }, { name: "Executable Property", value: "No" },
        { name: "Archive Property", value: "Yes" }, { name: "Structured Property", value: "Yes" },
        { name: "Unique Identifier", value: "pkg:npm/lodash@4.17.20" }, { name: "Component Supplier", value: "John-David Dalton" },
        { name: "Component Origin", value: "Open-source" }, { name: "Author of SBOM Data", value: "Example Org PSIRT" },
      ] },
    { "bom-ref": "internal", type: "library", name: "internal-auth-lib", version: "1.3.0", properties: [{ name: "Patch Status", value: "NA" }] },
  ],
  dependencies: [{ ref: "app", dependsOn: ["lodash", "internal"] }, { ref: "lodash", dependsOn: [] }, { ref: "internal", dependsOn: [] }],
  vulnerabilities: [{ id: "CVE-2021-23337", ratings: [{ severity: "high", score: 7.2 }], affects: [{ ref: "lodash" }],
    recommendation: "lodash 4.17.20: upgrade to 4.17.21", analysis: { state: "resolved" },
    properties: [{ name: "cert-in:priority", value: "P2 - high severity" }] }],
};

describe("conformance", () => {
  test("classifies every Table 5 field as present / declared NA / missing", () => {
    const c = sbomConformance(SBOM);
    const lodash = c.perComponent[0];
    expect(lodash.missing).toEqual([]);
    expect(lodash.na).toEqual(["End-of-Life (EOL) Date"]);
    const internal = c.perComponent[1];
    expect(internal.missing).toEqual(expect.arrayContaining(["Component Description", "Component License", "Checksums or Hashes",
      "Criticality", "Unique Identifier"]));
    expect(internal.missing).not.toContain("Component Dependencies"); // listed in the dependency graph
    const notInGraph = sbomConformance({ ...SBOM, dependencies: [{ ref: "app", dependsOn: ["lodash"] }] }).perComponent[0];
    expect(notInGraph.missing).toContain("Component Dependencies"); // absent from the graph = unknown
    expect(internal.na).toContain("Vulnerabilities"); // checked, nothing could be determined (Patch Status NA)
    expect(c.verdict).toBe("Not conformant");
    expect(c.fields).toHaveLength(21);
    expect(c.conformancePct).toBeGreaterThan(50);
    expect(c.conformancePct).toBeLessThan(100);
  });
});

describe("PDF report", () => {
  const pdfText = () => new PDFExportService().build(SBOM, SBOM.components).output();

  test("builds for CycloneDX 1.5 metadata (tools object) and shows real CERT-In values", () => {
    const out = pdfText();
    expect(out).toContain("CERT-In Table 5 conformance");
    expect(out).toContain("Generated by: syft 1.18.0");
    expect(out).toContain("Author of SBOM data: Example Org PSIRT");
    expect(out).toContain("Practices and Processes declared: 1/6");
    expect(out).toContain("Patch Status: Update available \\(>= 4.17.21\\)"); // PDF escapes parentheses
    expect(out).toContain("Component Supplier: John-David Dalton");
    expect(out).toContain("Release Date: 13-08-2020");
    expect(out).toContain("CVE-2021-23337");
    expect(out).toContain("Fixed"); // VEX status from analysis.state
    expect(out).toMatch(/Page 1 of \d+/);
    expect(out).not.toContain("Patch Status: Unknown");
  });

  test("exportDetailedPDF reports success instead of throwing", () => {
    const svc = new PDFExportService();
    svc.build = jest.fn(() => ({ save: jest.fn() }));
    expect(svc.exportDetailedPDF(SBOM, SBOM.components)).toEqual({ success: true, message: "Comprehensive PDF exported successfully!" });
  });
});
